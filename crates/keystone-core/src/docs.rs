const GENERATED_BANNER: &str =
    "<!-- Generated by cargo xtask docs / keystone-core::docs. Do not edit. -->\n\n";

pub fn metrics_markdown() -> String {
    let mut out = String::from(GENERATED_BANNER);
    out.push_str("# Metrics catalog\n\n");
    out.push_str("Unknown names are dropped at ingest. This table is the allowlist.\n\n");
    out.push_str("| Name | Type | Unit | Stability | Labels | Help |\n");
    out.push_str("|---|---|---|---|---|---|\n");
    for def in catalog() {
        let ty = match def.metric_type {
            MetricType::Counter => "counter",
            MetricType::Gauge => "gauge",
        };
        let stab = match def.stability {
            Stability::Stable => "stable",
            Stability::Experimental => "experimental",
        };
        let labels = if def.labels.is_empty() {
            "—".into()
        } else {
            def.labels.join(", ")
        };
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} | {} |\n",
            def.name, ty, def.unit, stab, labels, def.help
        ));
    }
    out
}

pub fn permissions_markdown() -> String {
    let mut out = String::from(GENERATED_BANNER);
    out.push_str("# Permissions\n\n");
    out.push_str("The ingest token is not a permission and cannot grant Docker manage.\n\n");
    out.push_str("| Permission | Description |\n|---|---|\n");
    for p in Permission::iter() {
        out.push_str(&format!("| `{}` | {} |\n", p.as_str(), p.description()));
    }
    out
}

pub fn docker_ops_markdown() -> String {
    let mut out = String::from(GENERATED_BANNER);
    out.push_str("# Docker operations\n\n");
    out.push_str(
        "The agent talks to Docker Engine. The server never opens a remote `docker.sock`.\n",
    );
    out.push_str("`docker.manage` is opt-in. Socket access is root-equivalent on that node.\n\n");
    out.push_str("| Operation | Mutating | Permission | Description |\n|---|---|---|---|\n");
    for op in DockerOp::iter() {
        out.push_str(&format!(
            "| `{}` | {} | `{}` | {} |\n",
            op.as_str(),
            if op.mutating() { "yes" } else { "no" },
            op.permission().as_str(),
            op.description()
        ));
    }
    out
}

