fn schema_markdown(title: &str, root: &RootSchema) -> String {
    let mut out = String::from(GENERATED_BANNER);
    out.push_str("# ");
    out.push_str(title);
    out.push_str("\n\nFields come from the Rust config structs (`schemars`).\n\n");
    if let Some(meta) = &root.schema.metadata {
        if let Some(desc) = &meta.description {
            out.push_str(desc);
            out.push_str("\n\n");
        }
    }
    out.push_str("| Field | Type | Description |\n|---|---|---|\n");
    render_object(&mut out, "", &root.schema, root);
    for (name, schema) in &root.definitions {
        if let Schema::Object(obj) = schema {
            out.push_str(&format!("\n## `{name}`\n\n"));
            if let Some(meta) = &obj.metadata {
                if let Some(desc) = &meta.description {
                    out.push_str(desc);
                    out.push_str("\n\n");
                }
            }
            out.push_str("| Field | Type | Description |\n|---|---|---|\n");
            render_object(&mut out, "", obj, root);
        }
    }
    out
}

fn render_object(out: &mut String, prefix: &str, obj: &SchemaObject, root: &RootSchema) {
    let Some(props) = obj.object.as_ref() else {
        return;
    };
    let mut names: Vec<_> = props.properties.keys().cloned().collect();
    names.sort();
    for name in names {
        let schema = &props.properties[&name];
        let field = if prefix.is_empty() {
            name.clone()
        } else {
            format!("{prefix}.{name}")
        };
        match schema {
            Schema::Object(child) => {
                let ty = type_name(child);
                let desc = child
                    .metadata
                    .as_ref()
                    .and_then(|m| m.description.clone())
                    .unwrap_or_default()
                    .replace('\n', " ");
                out.push_str(&format!("| `{field}` | {ty} | {desc} |\n"));
            }
            Schema::Bool(_) => {
                out.push_str(&format!("| `{field}` | unknown |  |\n"));
            }
        }
    }
    let _ = root;
}

fn type_name(obj: &SchemaObject) -> String {
    if let Some(reference) = &obj.reference {
        return reference
            .rsplit('/')
            .next()
            .unwrap_or(reference)
            .to_string();
    }
    if let Some(sub) = &obj.subschemas {
        if let Some(any) = &sub.any_of {
            if any.len() == 2 {
                return format!("optional {}", schema_type_label(&any[0]));
            }
        }
    }
    match &obj.instance_type {
        Some(SingleOrVec::Single(t)) => instance_type_name(**t, obj),
        Some(SingleOrVec::Vec(v)) => v
            .iter()
            .map(|t| instance_type_name(*t, obj))
            .collect::<Vec<_>>()
            .join(" | "),
        None => "object".into(),
    }
}

fn schema_type_label(schema: &Schema) -> String {
    match schema {
        Schema::Object(o) => type_name(o),
        Schema::Bool(_) => "any".into(),
    }
}

fn instance_type_name(t: InstanceType, obj: &SchemaObject) -> String {
    match t {
        InstanceType::String => "string".into(),
        InstanceType::Number => "number".into(),
        InstanceType::Integer => "integer".into(),
        InstanceType::Boolean => "boolean".into(),
        InstanceType::Array => {
            if let Some(arr) = &obj.array {
                if let Some(Schema::Object(item)) = arr.items.as_ref().and_then(|i| match i {
                    schemars::schema::SingleOrVec::Single(s) => Some(s.as_ref()),
                    _ => None,
                }) {
                    return format!("array of {}", type_name(item));
                }
            }
            "array".into()
        }
        InstanceType::Object => "object".into(),
        InstanceType::Null => "null".into(),
    }
}

pub fn json_schema_pretty(schema: &RootSchema) -> String {
    serde_json::to_string_pretty(schema).unwrap_or_else(|_| "{}".into())
}

